# A client's fiefs. A client who swore homage to a kingdom of the world holds centers in the host's world through a
# stand-in lord there: trp_tutorial_fighter_1 to _3 (Native's tutorial alone uses them), named and sworn as the client,
# vassal index 0 to 2 (the bridge gives the index, kind 45). The client's own game shows those centers as its own
# (lord trp_player), and the host's own ones under the host's image, trp_tutorial_fighter_4.
#
# A fief comes by the sword or by the king's grace: a center the vassal storms in a joint siege goes to the stand-in at
# once (coop_server_capture), and the vassal's king may grant one of the realm's lordless centers (the dialog below,
# &vr= to the bridge, kind 50 to the host's game, kind 46 back). Each week the host's game counts the rents and tariffs
# of the stand-ins' centers and what their garrisons cost (&vi=, totals since the campaign began); the bridge puts the
# difference into the vassal's purse and pays it out when the vassal plays (kind 47, &va= says it came). The garrison
# lives in the host's world: the vassal sees it as the bridge last heard of it (&vgl=, kind 49), leaves men or takes
# them on Native's exchange screen, and the change goes to the host's game (&vgd=, kind 51), which answers with the men
# no longer there (&fg=, kind 48): those leave the vassal's party again. A client's own game keeps no garrison and no
# rents in its copies of those centers: its weekly budget would pay and earn a second time.
#
# A player may give one of its fiefs to a friend it meets on the map, or from the camp's players menu (the host also a
# lordless center of its own realm, as its king): &fgv= to the bridge, kind 53 to the host's game, kind 54 back to both
# players. A friend who serves no kingdom of the world becomes a vassal of the host's own realm by it (its stand-in serves
# fac_player_supporters_faction); one who serves another kingdom than the center's cannot hold it.
#
# Client: $coop_vassal_slot its index + 1 (0: no fief holder); $coop_fief_state 0 nothing, 1 the garrison asked for,
# 2 it came, 3 on the screen, 4 the change on its way; $coop_fief_vr_token a grant asked for; $coop_host_wars the
# kingdoms the host's side fights, one bit each (kind 52).
# Both: $coop_fief_gv_token a gift on its way, to the player in slot $coop_fief_gv_slot, $coop_fief_gv_center.
# Host's game: $coop_fief_week the last week counted, $coop_fief_gn grants to answer, $coop_fief_ring_at the next
# entry of the ring of garrison changes, $coop_fief_fg_send those entries still to answer (one bit each).

