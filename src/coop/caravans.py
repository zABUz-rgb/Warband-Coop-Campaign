# Trade caravans of the players (1.2.0). A player buys one at the company's camp or from a town's guild master,
# gives it men and denars, and the bridge (tools/coop_bridge.py, cv) hands it to the host's game, where it is a
# party of the world like any other: it rides from town to town, buys where a good is cheap and sells where it is
# dear, and bandits and enemies may take it. Home, its denars go into the shared treasury and its men to the
# owner's camp (cve). Kingdoms at war with its owner or with the host keep it out of their towns.
#   42 (to the host) a caravan token|slot|type|denars|x|y|enemies|n|(troop, count)*n
#   43 (to the host) it is counted token        44 it set out token|done (0 refused: all comes back)
#
# Player: $coop_cv_step 0 none, 1 its guards, 2 its denars; $coop_cv_from 1 the camp, 2 a town ($coop_cv_town);
# $coop_cv_fee and $coop_cv_gold left the hero already; its guards wait in NOTES from coop_cv_pairs ($coop_cv_n
# stacks) from the first screen on, and are on p_temp_party only while the screen is open;
# $coop_cv_token: sent off, until the bridge answers.
# Host: the caravan's party slots (slot_party_coop_cv_...); those home wait in NOTES from coop_cv_ends.

NOTES = "trp_tutorial_student_3"


def request_token(token):
  return [(store_random_in_range, token, 1, 1000000000)]


def price_ops(dest, value, factor, percent):
  """Ops: dest = an item worth value at a town's price factor, the caravan's spread (percent) on it."""
  return [
    (store_mul, dest, value, factor),
    (val_div, dest, average_price_factor),
    (val_mul, dest, percent),
    (val_div, dest, 100),
    (val_max, dest, 1),
  ]


def step_ops(step, value):
  """Ops: step = what a unit bought or sold moves a town's price factor (as Native's game_event_buy_item)."""
  return [
    (assign, step, 0),
    (try_begin),
      (ge, value, 100),
      (store_sub, step, value, 100),
      (val_div, step, 8),
    (try_end),
  ]


